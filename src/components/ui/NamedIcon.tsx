export function NamedIcon({
  name,
  className,
  size = 18,
  color,
}: {
  name?: string
  className?: string
  size?: number
  color?: string
}) {
  const Icon = (name && MAP[name]) || Circle
  return <Icon className={className} size={size} color={color} strokeWidth={1.75} />
}
